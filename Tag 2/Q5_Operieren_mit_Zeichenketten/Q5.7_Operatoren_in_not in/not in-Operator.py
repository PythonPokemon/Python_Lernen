""" 
in-Operator (Teil in String enthalten?)
es wird geschaut ob ein Teilstring in einem String 'nicht' enthalten ist
und gibt entsprechend True oder False zurück.

"""
sprache = "JavaScript"

print("Java" not in sprache)    # False (weil es drin ist)
print("Python" not in sprache)  # True (weil es nicht drin ist)
