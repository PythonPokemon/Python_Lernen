"""
🟡 Mittlere Aufgabe
Wörter mit einem Trennzeichen verbinden

🧩 Lernziel: Lernen, wie .join() mit verschiedenen Trennzeichen funktioniert.
"""

namen = ["Anna", "Ben", "Chris"]
namen_kette = "---".join(namen)     # Verbindet mit 3x Bindestrichen
print(namen_kette)                 # Ausgabe: Anna---Ben---Chris
