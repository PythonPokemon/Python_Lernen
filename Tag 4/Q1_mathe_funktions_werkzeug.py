""" 
✅ 1. Was ist ein Modul?
Ein Modul ist einfach eine .py-Datei mit Funktionen oder Variablen, die man in anderen Dateien importieren kann.
"""

# Dies ist unser benutzerdefiniertes Modul
# Das jeweils zwei Methoden beinhalten: addiere und subtrahiere
# Diese dienen als Import demonstartion in den anderen  dateien!

def addiere(a, b):
    return a + b

def subtrahiere(a, b):
    return a - b
