"""
📌 Merke: Escape Charakter
Damit ist in Python das Escape-Zeichen \ (Backslash) gemeint.
Es kann die Bedeutung des darauffolgenden Zeichens verändern.
"""

# Das einfachste Beispiel:
print("Hallo\nWelt")    # \n bedeutet zeilenumbruch

print("\n")             # Zeilenumbruch

# -----------------------------------------------------------

# Noch mit Anführungszeichen
print("Er sagte: \"Hallo\"")    

"""
Normalerweise würde das " die Zeichenkette beenden. 
Durch \" wird das Anführungszeichen als normales Zeichen interpretiert.


Merksatz:
\ ist das Escape-Zeichen. Es verändert die Bedeutung des Zeichens, das direkt danach kommt.

Weitere Einsatzmöglichkeiten mit dem Escape Charakter:

\n   # Zeilenumbruch
\t   # Tabulator
\"   # Anführungszeichen
\\   # Backslash
"""